// GEO kit — 純粋関数ライブラリ（Node / Cloudflare Workers 両対応・依存なし）
export const MARKER = "Generated by geo-build.mjs";

const esc = (s) =>
  String(s).replace(/[&<>"']/g, (ch) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[ch]));
const baseOf = (c) => c.siteUrl.replace(/\/$/, "");
const absOf = (c) => (p) => (/^https?:\/\//.test(p) ? p : baseOf(c) + (p.startsWith("/") ? p : "/" + p));
const LOCALES = { ja: "ja_JP", en: "en_US" };

// ---- パスの正規化 ----
// "/about/" "/about.html" "/about/index.html" を "/about" として同じページ扱いにする
export function normPath(p) {
  let s = (p || "/").split(/[?#]/)[0];
  s = s.replace(/\/index\.html$/, "/").replace(/\.html$/, "");
  if (s.length > 1) s = s.replace(/\/+$/, "");
  return s.startsWith("/") ? s || "/" : "/" + s;
}

export function findPage(c, pathname) {
  const n = normPath(pathname);
  return c.pages.find((p) => normPath(p.path) === n);
}

// ---- 設定チェック ----
// errors: 生成できない（必須項目の欠落） / warnings: 生成はできるがサンプル値や不足がある
const SAMPLES = {
  name: /^プロダクト名$/,
  tagline: /^一行で言うと/,
  description: /AIや検索エンジンに読ませたい説明文/,
  text: /^主な機能|ここに/m,
};

export function checkConfig(c) {
  const errors = [];
  const warnings = [];
  for (const key of ["siteUrl", "name", "tagline", "description"]) {
    if (typeof c[key] !== "string" || !c[key].trim()) errors.push(`${key} が未設定です`);
  }
  if (!Array.isArray(c.pages) || c.pages.length === 0) errors.push("pages が空です（最低1ページ必要）");
  else
    c.pages.forEach((p, i) => {
      if (typeof p.path !== "string" || !p.path.startsWith("/")) errors.push(`pages[${i}].path は "/" で始めてください`);
      if (!p.title) errors.push(`pages[${i}].title が未設定です`);
    });
  if (c.siteUrl && !/^https?:\/\//.test(c.siteUrl)) errors.push("siteUrl は https:// から書いてください");
  if (errors.length) return { errors, warnings };

  if (/example\./.test(c.siteUrl)) warnings.push("siteUrl がサンプルのままです");
  if (SAMPLES.name.test(c.name)) warnings.push("name がサンプルのままです");
  if (SAMPLES.tagline.test(c.tagline)) warnings.push("tagline がサンプルのままです");
  if (SAMPLES.description.test(c.description)) warnings.push("description がサンプルのままです");
  else if (c.description.length < 50) warnings.push("description が短すぎます（50字以上推奨）");
  if (SAMPLES.text.test([...(c.features ?? []), ...(c.faq ?? []).map((f) => f.a)].join("\n")))
    warnings.push("features / faq にサンプル文が残っています");
  if (!c.ogImage) warnings.push("ogImage が未設定です（SNS・検索結果で画像が出ません）");
  const paths = c.pages.map((p) => normPath(p.path));
  if (new Set(paths).size !== paths.length) warnings.push("pages に同じパスが重複しています（末尾スラッシュ・.html 違いを含む）");
  return { errors, warnings };
}

// ---- robots.txt ----
export function buildRobots(c) {
  const abs = absOf(c);
  const dis = (c.aiCrawlers?.disallowPaths ?? []).map((p) => `Disallow: ${p}`).join("\n");
  // 個別の User-agent グループがあるクローラーは * を見ないので、Disallow も各グループに繰り返す
  const groups = [
    `User-agent: *\nAllow: /\n${dis}`.trim(),
    ...(c.aiCrawlers?.allow ?? []).map((ua) => `User-agent: ${ua}\nAllow: /\n${dis}`.trim()),
  ];
  return `# ${MARKER}
${groups.join("\n\n")}

Sitemap: ${abs("/sitemap.xml")}
`;
}

// ---- llms.txt (https://llmstxt.org 形式) ----
export function buildLlms(c) {
  const abs = absOf(c);
  const pages = c.pages.map((p) => `- [${p.title}](${abs(p.path)})${p.summary ? `: ${p.summary}` : ""}`).join("\n");
  const feats = (c.features ?? []).map((f) => `- ${f}`).join("\n");
  const faq = (c.faq ?? []).map((f) => `### ${f.q}\n${f.a}`).join("\n\n");
  const author = c.author?.name
    ? `\n## Optional\n- 作者: ${c.author.url ? `[${c.author.name}](${c.author.url})` : c.author.name}\n`
    : "";
  return `# ${c.name}

> ${c.tagline}

${c.description}

## Pages
${pages}
${feats ? `\n## Features\n${feats}\n` : ""}${faq ? `\n## FAQ\n${faq}\n` : ""}${author}
<!-- ${MARKER} -->
`;
}

// ---- sitemap.xml ----
// lastmod: pages[].lastmod があればそれを使う。無ければ引数 lastmod（省略時は出力しない）
// ※ Worker から毎回「今日」を返すと不正確な lastmod になり、検索エンジンに無視されるため
export function buildSitemap(c, lastmod) {
  const abs = absOf(c);
  const urls = c.pages
    .map((p) => {
      const lm = p.lastmod ?? lastmod;
      return `  <url>
    <loc>${esc(abs(p.path))}</loc>${lm ? `\n    <lastmod>${esc(lm)}</lastmod>` : ""}
    <changefreq>${p.changefreq ?? "monthly"}</changefreq>
    <priority>${Number(p.priority ?? 0.5).toFixed(1)}</priority>
  </url>`;
    })
    .join("\n");
  return `<?xml version="1.0" encoding="UTF-8"?>
<!-- ${MARKER} -->
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${urls}
</urlset>
`;
}

// ---- JSON-LD ----
export function buildJsonLd(c) {
  const base = baseOf(c);
  const graph = [
    {
      "@type": "SoftwareApplication",
      name: c.name,
      description: c.description,
      url: base + "/",
      applicationCategory: c.app?.category ?? "WebApplication",
      operatingSystem: c.app?.os ?? "Web",
      ...(c.lang && { inLanguage: c.lang }),
      ...(c.ogImage && { image: absOf(c)(c.ogImage) }),
      ...(c.app?.price != null && {
        offers: { "@type": "Offer", price: c.app.price, priceCurrency: c.app.priceCurrency ?? "JPY" },
      }),
      ...(c.features?.length && { featureList: c.features }),
      ...(c.author?.name && {
        author: { "@type": "Person", name: c.author.name, ...(c.author.url && { url: c.author.url }) },
      }),
    },
  ];
  if (c.faq?.length) {
    graph.push({
      "@type": "FAQPage",
      mainEntity: c.faq.map((f) => ({
        "@type": "Question",
        name: f.q,
        acceptedAnswer: { "@type": "Answer", text: f.a },
      })),
    });
  }
  // </script> 混入対策
  return JSON.stringify({ "@context": "https://schema.org", "@graph": graph }, null, 2).replace(/</g, "\\u003c");
}

// ---- <head> に入れるタグ ----
export function buildHead(c, pagePath = "/") {
  const abs = absOf(c);
  const page = findPage(c, pagePath) ?? c.pages[0];
  const isTop = normPath(page.path) === "/";
  const title = isTop ? `${c.name} | ${c.tagline}` : `${page.title} | ${c.name}`;
  const desc = isTop ? c.description : page.summary || c.description;
  const locale = LOCALES[c.lang];
  return `<!-- GEO: ${MARKER} -->
<title>${esc(title)}</title>
<meta name="description" content="${esc(desc)}">
<link rel="canonical" href="${esc(abs(page.path))}">
<meta property="og:type" content="website">
<meta property="og:site_name" content="${esc(c.name)}">
<meta property="og:title" content="${esc(title)}">
<meta property="og:description" content="${esc(desc)}">
<meta property="og:url" content="${esc(abs(page.path))}">${
    c.ogImage ? `\n<meta property="og:image" content="${esc(abs(c.ogImage))}">` : ""
  }${locale ? `\n<meta property="og:locale" content="${locale}">` : ""}
<meta name="twitter:card" content="${c.ogImage ? "summary_large_image" : "summary"}">
<link rel="alternate" type="text/plain" title="llms.txt" href="/llms.txt">
<script type="application/ld+json">
${buildJsonLd(c)}
</script>
<!-- /GEO -->`;
}

// ---- 静的 HTML への注入（geo-build.mjs --inject 用） ----
// 既存の GEO ブロックと、GEO が出力するのと同種のタグを <head> から除いてから </head> 直前に入れる。
// 何度実行しても同じ結果になる（冪等）。
const GEO_BLOCK = /[ \t]*<!-- GEO:[\s\S]*?<!-- \/GEO -->[ \t]*\r?\n?/g;
const DUP_TAGS = [
  /[ \t]*<title\b[^>]*>[\s\S]*?<\/title>[ \t]*\r?\n?/gi,
  /[ \t]*<meta\b[^>]*\bname\s*=\s*["'](?:description|twitter:[^"']*)["'][^>]*>[ \t]*\r?\n?/gi,
  /[ \t]*<meta\b[^>]*\bproperty\s*=\s*["']og:[^"']*["'][^>]*>[ \t]*\r?\n?/gi,
  /[ \t]*<link\b[^>]*\brel\s*=\s*["']canonical["'][^>]*>[ \t]*\r?\n?/gi,
  /[ \t]*<script\b[^>]*\btype\s*=\s*["']application\/ld\+json["'][^>]*>[\s\S]*?<\/script>[ \t]*\r?\n?/gi,
];

export function injectHeadHtml(html, head) {
  const m = /<head\b[^>]*>([\s\S]*?)<\/head>/i.exec(html);
  if (!m) return { html, removed: 0, ok: false };
  let inner = m[1].replace(GEO_BLOCK, "");
  let removed = 0;
  for (const re of DUP_TAGS) {
    inner = inner.replace(re, () => {
      removed++;
      return "";
    });
  }
  inner = inner.replace(/\s*$/, "\n") + head + "\n";
  const start = m.index + m[0].indexOf(">") + 1;
  return { html: html.slice(0, start) + inner + html.slice(start + m[1].length), removed, ok: true };
}
