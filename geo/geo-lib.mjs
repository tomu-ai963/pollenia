// GEO kit — 純粋関数ライブラリ（Node / Cloudflare Workers 両対応・依存なし）
// 版の番号。組み込み先のテストで照合すると、コピー元（kit 本体）とのずれに気づける
export const VERSION = "1.0.0";
export const MARKER = "Generated by GEO Kit";
// 1.0.0 より前の印。既存の生成物を手書きと誤認しないよう、まだ受け付ける
const LEGACY_MARKER = "Generated by geo-build.mjs";

/** GEO Kit が作ったファイルか（印を含むか） */
export function isGenerated(text) {
  return text.includes(MARKER) || text.includes(LEGACY_MARKER);
}

const esc = (s) =>
  String(s).replace(/[&<>"']/g, (ch) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[ch]));
const baseOf = (c) => c.siteUrl.replace(/\/$/, "");
const absOf = (c) => (p) => (/^https?:\/\//.test(p) ? p : baseOf(c) + (p.startsWith("/") ? p : "/" + p));
const LOCALES = { ja: "ja_JP", en: "en_US" };

// ---- パスの正規化 ----
// "/about/" "/about.html" "/about/index.html" を "/about" として同じページ扱いにする
export function normPath(p) {
  let s = (p || "/").split(/[?#]/)[0];
  s = s.replace(/\/index\.html$/, "/").replace(/\.html$/, "");
  if (s.length > 1) s = s.replace(/\/+$/, "");
  return s.startsWith("/") ? s || "/" : "/" + s;
}

// 検索結果の説明文（<meta name="description"> / og:description）。長いと途中で切れる
export const META_DESC_MAX = 160;

/** そのページの説明文: pages[].metaDescription > （トップ以外）summary > metaDescription > description */
export function metaDescOf(c, page) {
  const site = c.metaDescription || c.description;
  if (page.metaDescription) return page.metaDescription;
  return normPath(page.path) === "/" ? site : page.summary || site;
}

/** FAQ の JSON-LD を入れるページか: pages[].faq を書けばそれ、書かなければトップだけ */
export function faqOn(c, page) {
  if (!c.faq?.length || !page) return false;
  return page.faq ?? normPath(page.path) === "/";
}

export function findPage(c, pathname) {
  const n = normPath(pathname);
  return c.pages.find((p) => normPath(p.path) === n);
}

// ---- 料金（app.offers） ----
// period: 継続課金の単位。JSON-LD では UnitPriceSpecification（billingDuration）、llms.txt では「月額」などで書く
const PRICE = /^\d+(\.\d+)?$/;
const PERIODS = {
  month: { duration: "P1M", unit: "MON", ja: "月額", en: "month" },
  year: { duration: "P1Y", unit: "ANN", ja: "年額", en: "year" },
};

function priceText(c, o) {
  const cur = o.priceCurrency ?? c.app?.priceCurrency ?? "JPY";
  const p = PERIODS[o.period];
  if (c.lang === "ja") {
    if (Number(o.price) === 0) return "無料";
    const amount = cur === "JPY" ? `${Number(o.price).toLocaleString("ja-JP")} 円` : `${o.price} ${cur}`;
    return p ? `${p.ja} ${amount}` : amount;
  }
  if (Number(o.price) === 0) return "Free";
  return `${o.price} ${cur}${p ? ` / ${p.en}` : ""}`;
}

function offerLd(c, o) {
  const priceCurrency = o.priceCurrency ?? c.app?.priceCurrency ?? "JPY";
  const p = PERIODS[o.period];
  return {
    "@type": "Offer",
    ...(o.name && { name: o.name }),
    price: String(o.price),
    priceCurrency,
    ...(o.description && { description: o.description }),
    ...(p && {
      priceSpecification: {
        "@type": "UnitPriceSpecification",
        price: String(o.price),
        priceCurrency,
        billingDuration: p.duration,
        unitCode: p.unit,
      },
    }),
  };
}

// ---- 設定チェック ----
// errors: 生成できない（必須項目の欠落） / warnings: 生成はできるがサンプル値や不足がある
const SAMPLES = {
  name: /^プロダクト名$/,
  tagline: /^一行で言うと/,
  description: /AIや検索エンジンに読ませたい説明文/,
  text: /^主な機能|ここに/m,
};

export function checkConfig(c) {
  const errors = [];
  const warnings = [];
  for (const key of ["siteUrl", "name", "tagline", "description"]) {
    if (typeof c[key] !== "string" || !c[key].trim()) errors.push(`${key} が未設定です`);
  }
  if (!Array.isArray(c.pages) || c.pages.length === 0) errors.push("pages が空です（最低1ページ必要）");
  else
    c.pages.forEach((p, i) => {
      if (typeof p.path !== "string" || !p.path.startsWith("/")) errors.push(`pages[${i}].path は "/" で始めてください`);
      if (!p.title) errors.push(`pages[${i}].title が未設定です`);
      if (p.faq != null && typeof p.faq !== "boolean") errors.push(`pages[${i}].faq は true か false です`);
    });
  if (c.siteUrl && !/^https?:\/\//.test(c.siteUrl)) errors.push("siteUrl は https:// から書いてください");
  if (errors.length) return { errors, warnings };

  if (/example\./.test(c.siteUrl)) warnings.push("siteUrl がサンプルのままです");
  if (SAMPLES.name.test(c.name)) warnings.push("name がサンプルのままです");
  if (SAMPLES.tagline.test(c.tagline)) warnings.push("tagline がサンプルのままです");
  if (SAMPLES.description.test(c.description)) warnings.push("description がサンプルのままです");
  else if (c.description.length < 50) warnings.push("description が短すぎます（50字以上推奨）");
  c.pages.forEach((p) => {
    const d = metaDescOf(c, p);
    if (d.length > META_DESC_MAX) {
      const src = p.metaDescription ? `pages(${p.path}).metaDescription` : normPath(p.path) !== "/" && p.summary ? `pages(${p.path}).summary` : c.metaDescription ? "metaDescription" : "description";
      const fix = src === "description" ? "。検索用の短い説明文を metaDescription に書いてください（description は llms.txt・JSON-LD 用にそのまま使えます）" : "";
      warnings.push(`${src} が ${d.length} 字で、検索結果の説明文としては長すぎます（${META_DESC_MAX} 字以内推奨。${p.path} の meta description）${fix}`);
    }
  });
  if (SAMPLES.text.test([...(c.features ?? []), ...(c.faq ?? []).map((f) => f.a)].join("\n")))
    warnings.push("features / faq にサンプル文が残っています");
  if (!c.ogImage) warnings.push("ogImage が未設定です（SNS・検索結果で画像が出ません）");
  if (c.app?.offers != null) {
    if (!Array.isArray(c.app.offers) || c.app.offers.length === 0) errors.push("app.offers は1件以上の配列にしてください");
    else
      c.app.offers.forEach((o, i) => {
        if (!o?.name) errors.push(`app.offers[${i}].name が未設定です`);
        if (!PRICE.test(String(o?.price ?? ""))) errors.push(`app.offers[${i}].price は "300" のような数字で書いてください`);
        if (o?.period != null && !PERIODS[o.period]) errors.push(`app.offers[${i}].period は "month" か "year" です`);
      });
    if (c.app.price != null) warnings.push("app.price は app.offers があるので使われません（どちらか一方に）");
  }
  if (c.guide != null) {
    const g = c.guide;
    if (typeof g.path !== "string" || !/^\/[^?#]*\.txt$/.test(g.path)) errors.push('guide.path は "/llms-full.txt" のように / で始まる .txt にしてください');
    for (const key of ["title", "summary", "lead"]) if (!g[key]) errors.push(`guide.${key} が未設定です`);
    if (!Array.isArray(g.sections) || g.sections.length === 0) errors.push("guide.sections が空です");
    else {
      const headings = new Set(g.sections.map((s) => s.heading));
      (g.readingMap ?? []).forEach((r) => {
        if (!headings.has(r.section)) errors.push(`guide.readingMap の「${r.section}」は sections にありません`);
      });
      g.sections.forEach((s, i) => {
        if (s.from && !["features", "faq"].includes(s.from)) errors.push(`guide.sections[${i}].from は "features" か "faq" です`);
      });
    }
  }
  if (c.docs != null) {
    if (!Array.isArray(c.docs)) errors.push("docs は配列にしてください");
    else
      c.docs.forEach((d, i) => {
        if (!d?.title) errors.push(`docs[${i}].title が未設定です`);
        if (typeof d?.url !== "string" || !/^(https?:\/\/|\/)/.test(d.url)) errors.push(`docs[${i}].url は "/" か https:// で始めてください`);
      });
  }
  if (c.publisher != null && !c.publisher?.name) errors.push("publisher.name が未設定です");
  if (c.body != null) {
    const items = c.body.items;
    if (items !== "features" && !(Array.isArray(items) && items.length))
      errors.push('body.items は文の配列か "features" にしてください');
  }
  const paths = c.pages.map((p) => normPath(p.path));
  if (new Set(paths).size !== paths.length) warnings.push("pages に同じパスが重複しています（末尾スラッシュ・.html 違いを含む）");
  return { errors, warnings };
}

// ---- robots.txt ----
export function buildRobots(c) {
  const abs = absOf(c);
  const dis = (c.aiCrawlers?.disallowPaths ?? []).map((p) => `Disallow: ${p}`).join("\n");
  // 個別の User-agent グループがあるクローラーは * を見ないので、Disallow も各グループに繰り返す
  const groups = [
    `User-agent: *\nAllow: /\n${dis}`.trim(),
    ...(c.aiCrawlers?.allow ?? []).map((ua) => `User-agent: ${ua}\nAllow: /\n${dis}`.trim()),
  ];
  return `# ${MARKER}
${groups.join("\n\n")}

Sitemap: ${abs("/sitemap.xml")}
`;
}

// ---- llms.txt (https://llmstxt.org 形式) ----
export function buildLlms(c) {
  const abs = absOf(c);
  const pages = c.pages.map((p) => `- [${p.title}](${abs(p.path)})${p.summary ? `: ${p.summary}` : ""}`).join("\n");
  const feats = (c.features ?? []).map((f) => `- ${f}`).join("\n");
  const faq = (c.faq ?? []).map((f) => `### ${f.q}\n${f.a}`).join("\n\n");
  // 料金は app.offers を書いたときだけ節にする（従来の app.price だけの設定では出力を変えない）
  const pricing = Array.isArray(c.app?.offers)
    ? c.app.offers
        .map((o) => `- ${o.name}: ${priceText(c, o)}${o.description ? (c.lang === "ja" ? `（${o.description}）` : ` (${o.description})`) : ""}`)
        .join("\n")
    : "";
  // ## Docs: 使い方ガイド（guide）と、設定の docs に書いたリンク
  const docs = [
    ...(c.guide ? [`- [${c.guide.title}](${abs(c.guide.path)}): ${c.guide.summary}`] : []),
    ...(c.docs ?? []).map((d) => `- [${d.title}](${abs(d.url)})${d.summary ? `: ${d.summary}` : ""}`),
  ].join("\n");
  const link = (who) => (who.url ? `[${who.name}](${who.url})` : who.name);
  const en = c.lang === "en";
  const credits = [
    ...(c.author?.name ? [`- ${en ? "Author" : "作者"}: ${link(c.author)}`] : []),
    ...(c.publisher?.name ? [`- ${en ? "Publisher" : "運営"}: ${link(c.publisher)}`] : []),
  ].join("\n");
  const author = credits ? `\n## Optional\n${credits}\n` : "";
  return `# ${c.name}

> ${c.tagline}

${c.description}

## Pages
${pages}
${docs ? `\n## Docs\n${docs}\n` : ""}${feats ? `\n## Features\n${feats}\n` : ""}${pricing ? `\n## Pricing\n${pricing}\n` : ""}${faq ? `\n## FAQ\n${faq}\n` : ""}${author}
<!-- ${MARKER} -->
`;
}

// ---- sitemap.xml ----
// lastmod: pages[].lastmod があればそれを使う。無ければ引数 lastmod（省略時は出力しない）
// ※ Worker から毎回「今日」を返すと不正確な lastmod になり、検索エンジンに無視されるため
export function buildSitemap(c, lastmod) {
  const abs = absOf(c);
  const urls = c.pages
    .map((p) => {
      const lm = p.lastmod ?? lastmod;
      return `  <url>
    <loc>${esc(abs(p.path))}</loc>${lm ? `\n    <lastmod>${esc(lm)}</lastmod>` : ""}
    <changefreq>${p.changefreq ?? "monthly"}</changefreq>
    <priority>${Number(p.priority ?? 0.5).toFixed(1)}</priority>
  </url>`;
    })
    .join("\n");
  return `<?xml version="1.0" encoding="UTF-8"?>
<!-- ${MARKER} -->
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${urls}
</urlset>
`;
}

// ---- JSON-LD ----
// pagePath: FAQ を出すかをページごとに決める（faqOn）。省略時はトップページとして扱う
export function buildJsonLd(c, pagePath = "/") {
  const base = baseOf(c);
  const graph = [
    {
      "@type": "SoftwareApplication",
      name: c.name,
      description: c.description,
      url: base + "/",
      applicationCategory: c.app?.category ?? "WebApplication",
      operatingSystem: c.app?.os ?? "Web",
      ...(c.lang && { inLanguage: c.lang }),
      ...(c.ogImage && { image: absOf(c)(c.ogImage) }),
      ...(Array.isArray(c.app?.offers)
        ? { offers: c.app.offers.map((o) => offerLd(c, o)) }
        : c.app?.price != null && {
            offers: { "@type": "Offer", price: c.app.price, priceCurrency: c.app.priceCurrency ?? "JPY" },
          }),
      ...(c.features?.length && { featureList: c.features }),
      ...(c.author?.name && {
        author: { "@type": "Person", name: c.author.name, ...(c.author.url && { url: c.author.url }) },
      }),
      ...(c.publisher?.name && {
        publisher: { "@type": "Organization", name: c.publisher.name, ...(c.publisher.url && { url: c.publisher.url }) },
      }),
    },
  ];
  // Google の指針では FAQ の構造化データは「そのページに FAQ が表示されていること」が前提
  if (faqOn(c, findPage(c, pagePath) ?? c.pages[0])) {
    graph.push({
      "@type": "FAQPage",
      mainEntity: c.faq.map((f) => ({
        "@type": "Question",
        name: f.q,
        acceptedAnswer: { "@type": "Answer", text: f.a },
      })),
    });
  }
  // </script> 混入対策
  return JSON.stringify({ "@context": "https://schema.org", "@graph": graph }, null, 2).replace(/</g, "\\u003c");
}

// ---- <head> に入れるタグ ----
export function buildHead(c, pagePath = "/") {
  const abs = absOf(c);
  const page = findPage(c, pagePath) ?? c.pages[0];
  const isTop = normPath(page.path) === "/";
  const title = isTop ? `${c.name} | ${c.tagline}` : `${page.title} | ${c.name}`;
  const desc = metaDescOf(c, page);
  const locale = LOCALES[c.lang];
  return `<!-- GEO: ${MARKER} -->
<title>${esc(title)}</title>
<meta name="description" content="${esc(desc)}">
<link rel="canonical" href="${esc(abs(page.path))}">
<meta property="og:type" content="website">
<meta property="og:site_name" content="${esc(c.name)}">
<meta property="og:title" content="${esc(title)}">
<meta property="og:description" content="${esc(desc)}">
<meta property="og:url" content="${esc(abs(page.path))}">${
    c.ogImage ? `\n<meta property="og:image" content="${esc(abs(c.ogImage))}">` : ""
  }${locale ? `\n<meta property="og:locale" content="${locale}">` : ""}
<meta name="twitter:card" content="${c.ogImage ? "summary_large_image" : "summary"}">
<link rel="alternate" type="text/plain" title="llms.txt" href="/llms.txt">
<script type="application/ld+json">
${buildJsonLd(c, page.path)}
</script>
<!-- /GEO -->`;
}

// ---- 静的 HTML への注入（geo-build.mjs --inject 用） ----
// 既存の GEO ブロックと、GEO が出力するのと同種のタグを <head> から除いてから </head> 直前に入れる。
// 何度実行しても同じ結果になる（冪等）。
const GEO_BLOCK = /[ \t]*<!-- GEO:[\s\S]*?<!-- \/GEO -->[ \t]*\r?\n?/g;
const DUP_TAGS = [
  /[ \t]*<title\b[^>]*>[\s\S]*?<\/title>[ \t]*\r?\n?/gi,
  /[ \t]*<meta\b[^>]*\bname\s*=\s*["'](?:description|twitter:[^"']*)["'][^>]*>[ \t]*\r?\n?/gi,
  /[ \t]*<meta\b[^>]*\bproperty\s*=\s*["']og:[^"']*["'][^>]*>[ \t]*\r?\n?/gi,
  /[ \t]*<link\b[^>]*\brel\s*=\s*["']canonical["'][^>]*>[ \t]*\r?\n?/gi,
  /[ \t]*<script\b[^>]*\btype\s*=\s*["']application\/ld\+json["'][^>]*>[\s\S]*?<\/script>[ \t]*\r?\n?/gi,
];

export function injectHeadHtml(html, head) {
  const m = /<head\b[^>]*>([\s\S]*?)<\/head>/i.exec(html);
  if (!m) return { html, removed: 0, ok: false };
  let inner = m[1].replace(GEO_BLOCK, "");
  let removed = 0;
  for (const re of DUP_TAGS) {
    inner = inner.replace(re, () => {
      removed++;
      return "";
    });
  }
  // 既存のタグの字下げにそろえる（JSON-LD の中身も同じだけ下げる）。
  // 取り除く前の中身から測るので、2回目（GEO ブロックしか残っていない）も同じ字下げになる
  const indent = /\n([ \t]+)</.exec(m[1])?.[1] ?? "";
  const block = head.split("\n").map((l) => (l ? indent + l : l)).join("\n");
  inner = inner.replace(/\s*$/, "\n") + block + "\n";
  const start = m.index + m[0].indexOf(">") + 1;
  return { html: html.slice(0, start) + inner + html.slice(start + m[1].length), removed, ok: true };
}

// ---- 本文の紹介文（JS を実行しないクローラー・初めて来た人向け） ----
// HTML に置いた <!-- GEO-BODY --><!-- /GEO-BODY --> の間を、body の設定から作ったブロックで入れ替える。
// SPA の #root の中に置けば、JS が描画するまでの間だけ表示され、クローラーには本文として読める。
//   body: {
//     tag?: "div" | "main" | "section",     // 外側の要素（既定 div）
//     heading?: true | string,               // 見出し h1（true なら name）
//     lead?: true | string,                  // 導入の一文 p（true なら tagline）
//     items: string[] | "features",          // 箇条書き ul（"features" なら features をそのまま）
//     classes?: { root?, heading?, lead?, list? }  // CSS のクラス（Tailwind などに合わせる）
//   }
const BODY_TAGS = new Set(["div", "main", "section"]);

export function buildBody(c) {
  const b = c.body;
  const cls = (k) => (b.classes?.[k] ? ` class="${esc(b.classes[k])}"` : "");
  const tag = BODY_TAGS.has(b.tag) ? b.tag : "div";
  const heading = b.heading === true ? c.name : b.heading;
  const lead = b.lead === true ? c.tagline : b.lead;
  const items = b.items === "features" ? c.features ?? [] : b.items ?? [];
  const lines = [
    `<${tag}${cls("root")}>`,
    ...(heading ? [`  <h1${cls("heading")}>${esc(heading)}</h1>`] : []),
    ...(lead ? [`  <p${cls("lead")}>${esc(lead)}</p>`] : []),
    ...(items.length ? [`  <ul${cls("list")}>`, ...items.map((t) => `    <li>${esc(t)}</li>`), "  </ul>"] : []),
    `</${tag}>`,
  ];
  return [`<!-- GEO-BODY: ${MARKER} -->`, ...lines, "<!-- /GEO-BODY -->"].join("\n");
}

const BODY_BLOCK = /([ \t]*)<!-- GEO-BODY(?::[^>]*)? -->[\s\S]*?<!-- \/GEO-BODY -->/;

/** GEO-BODY の目印があれば入れ替える（目印の行の字下げにそろえる）。目印が無ければ found: false */
export function injectBodyHtml(html, body) {
  const m = BODY_BLOCK.exec(html);
  if (!m) return { html, found: false };
  const indent = m[1];
  const block = body.split("\n").map((l, i) => (i === 0 ? indent + l : l ? indent + l : l)).join("\n");
  return { html: html.slice(0, m.index) + block + html.slice(m.index + m[0].length), found: true };
}

// ---- _headers（Cloudflare Workers の静的アセット / Cloudflare Pages） ----
// 静的アセットは .txt を charset なしの text/plain で返すため、日本語の llms.txt が化けうる
// （wrangler dev は charset を付けるので、ローカルでは気づけない）。_headers で付ける。
// extraPaths: llms-full.txt など、ほかに charset を付けたい .txt
export function buildHeaders(c, extraPaths = []) {
  const paths = ["/llms.txt", ...extraPaths, "/robots.txt"];
  const rules = [...new Set(paths)].map((p) => `${p}\n  Content-Type: text/plain; charset=utf-8`).join("\n");
  // コメントは ASCII だけにする（_headers は設定ファイルなので、文字コードの扱いに頼らない）
  return `# GEO: ${MARKER} (charset=utf-8 for text files; static assets omit it in production)
${rules}
# /GEO`;
}

const HEADERS_BLOCK = /# GEO:[^\n]*\n[\s\S]*?# \/GEO[ \t]*/;

/** _headers の GEO ブロックを入れ替える。無ければ末尾に足す（ほかのルールには触れない） */
export function injectHeadersText(text, block) {
  if (HEADERS_BLOCK.test(text)) return text.replace(HEADERS_BLOCK, block);
  const base = text.replace(/\s*$/, "");
  return (base ? base + "\n\n" : "") + block + "\n";
}

// ---- 使い方ガイド（guide。既定は /llms-full.txt） ----
// 利用者が URL を自分の AI（ChatGPT・Claude など）に渡して、使い方を聞くための説明書。
// llms.txt（概要。検索・GEO 向け）とは読み手が違う。開いた AI が最初の数行で「どこを読めばいいか」と
// 「答えるときに守ること」が分かるよう、冒頭に読む章の対応表と AI へのお願いを置き、目次は章の見出しから作る。
//   guide: {
//     path, title, summary,       // llms.txt の ## Docs からリンクする（summary はその説明）
//     lead,                        // 冒頭の一文
//     aiNotes: string[],           // 答えるときのお願い
//     readingMap: [{ ask, section }],  // 利用者が知りたいこと → 読む章（section は sections の heading）
//     sections: [{ heading, from?: "features" | "faq", lead?, items?, subsections?: [{ heading, items }] }]
//   }
// 章の from は本文を設定のほかの項目から作る印（features = description と機能一覧、faq = FAQ）。
// llms.txt・JSON-LD と同じ文を使い、料金などが片方だけ古くなるのを防ぐ。
export function buildGuide(c) {
  const g = c.guide;
  const base = baseOf(c);
  const bullets = (items) => (items ?? []).map((t) => `- ${t}`).join("\n");
  const bodyOf = (s) => {
    const parts = [];
    if (s.from === "features") parts.push(`${c.description}\n\n主な機能:\n${bullets(c.features)}`);
    if (s.from === "faq") parts.push((c.faq ?? []).map((f) => `### ${f.q}\n${f.a}`).join("\n\n"));
    if (s.lead) parts.push(s.lead);
    if (s.items?.length) parts.push(bullets(s.items));
    for (const sub of s.subsections ?? []) parts.push(`### ${sub.heading}\n${bullets(sub.items)}`);
    return parts.join("\n\n");
  };
  const map = (g.readingMap ?? []).map((r) => `| ${r.ask} | ${r.section} |`).join("\n");
  const toc = g.sections.map((s) => `- ${s.heading}`).join("\n");
  const sections = g.sections.map((s) => `## ${s.heading}\n\n${bodyOf(s)}`).join("\n\n");
  return `# ${c.name} ${g.title}

> ${g.lead}

- サイト: ${base}/
- この説明書: ${base}${g.path}

## AI の方へ（最初にお読みください）

利用者が知りたいことに応じて、次の章を読んでください。

| 利用者が知りたいこと | 読む章 |
|---|---|
${map}

答えるときのお願い:

${bullets(g.aiNotes)}

## 目次

${toc}

${sections}

<!-- ${MARKER} -->
`;
}
